import Foundation

public protocol Refining: Sendable {
    /// LLM が使えるか。Apple Intelligence が無効な環境では false。
    var isAvailable: Bool { get }

    /// モデルを事前ロードする。起動時に一度呼ぶ。
    func prewarm() async

    /// 整形する。タイムアウトまたは失敗時は nil を返し、呼び出し側が生テキストへ縮退する。
    ///
    /// **`timeout` は実時間の上限として守られる。** 打ち切った生成の完了は待たない。
    /// ただし打ち切った生成はデーモン側で走り続けうる（cancel は送るが応答は保証されない）。
    func refine(
        _ raw: String, locale: Locale, terms: [VocabularyTerm], timeout: Duration
    ) async -> String?
}

/// テスト用。指定した遅延の後に指定した結果を返す。
public struct StubRefiner: Refining {
    private let result: String?
    private let delay: Duration

    public init(result: String?, delay: Duration) {
        self.result = result
        self.delay = delay
    }

    public var isAvailable: Bool { result != nil }

    public func prewarm() async {}

    public func refine(
        _ raw: String, locale: Locale, terms: [VocabularyTerm], timeout: Duration
    ) async -> String? {
        guard let result, RefinementGuard.isRefinable(raw) else { return nil }
        return await withTimeout(timeout) { [delay] in
            try? await Task.sleep(for: delay)
            return Task.isCancelled ? nil : result
        }
    }
}

/// 整形として受け入れてよい入力・出力かの判定。
///
/// 整形の中身は LLM に委ねるしかないが、「整形と呼べる形をしているか」だけは
/// 手元で判定できる。ここを通らなかった出力は捨てて生テキストへ縮退する。
enum RefinementGuard {

    /// 整形しても意味の無い入力を弾く。空白だけの認識結果に LLM を回すと、
    /// 何も得ないまま挿入がタイムアウトぶん遅れる。
    static func isRefinable(_ raw: String) -> Bool {
        !raw.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// 出力が `raw` の整形結果として妥当な長さに収まっているか。
    ///
    /// 整形は「フィラーを削り、言い直しを畳み、句読点を補う」操作なので、出力が入力より
    /// 大きく伸びることはない。実測（12 発話・新規セッション・temperature 0）でも
    /// 出力 / 入力 は最大 1.00、増分は最大 0 字だった。
    ///
    /// 一方、発話が命令文に読めるとモデルは整形ではなく**その依頼への回答**を返す。
    /// 実測では 5 発話中 4 発話が再現性 100 % で逸脱し、出力は入力の 2.6〜25.6 倍
    /// （+39〜+639 字）へ膨らんで Python のコード片や手順書が混ざった。
    /// 逸脱の多くは生成に 1.3〜3.4 秒掛かってタイムアウトで落ちるが、実測 0.505 秒の
    /// 例があり、既定のタイムアウト（750 ms）をすり抜けてユーザーのテキスト欄へ入りうる。
    /// **逸脱を止めるのはタイムアウトではなくこの検査である。**
    ///
    /// 句読点の補完と正規表記への置換（例: ジーエイエス → Google Apps Script）で
    /// 多少は伸びるため、比だけでなく短文向けの下駄も併せて許容量を決める。
    static func isPlausible(_ output: String, refinementOf raw: String) -> Bool {
        output.count <= max(raw.count * 3 / 2, raw.count + shortInputAllowance)
    }

    /// 短い入力で比が跳ねるぶんの下駄。「はい」→「はい。」を落とさないために要る。
    private static let shortInputAllowance = 16

    /// 整形された発話にコードフェンスは現れない。現れたらそれは整形ではなく、
    /// 依頼を実行した結果のコード片である。
    ///
    /// ## この門は今や**単独では効かない**（変異 G6 / G6b が生き残った理由）
    ///
    /// 最終レビューの変異検査で、`accept` からこの条件を外しても、
    /// `containsCodeFence` が常に false を返すようにしても、全件緑だった。
    /// **理由は「追加字数の検査が同じ出力を落とすから」である。**
    /// バッククォート（U+0060）は Unicode の分類が Sk（記号）で、
    /// `freelyInsertable`（空白 + 句読点）に**入らない**。だからフェンス 1 個で
    /// 追加 3 字となり、許容量 0 の検査に必ず引っ掛かる。
    ///
    /// **重複していること自体は欠陥ではない。欠陥だったのは「独立に要る」と書いてあったことである。**
    /// 旧 doc は「`isPlausible` は長さしか見ないので短いコード片が素通りする」と書いていたが、
    /// 素通りの受け手はコードフェンスではなく追加字数の検査だった。
    ///
    /// **残してある理由は 2 つ。**
    /// 1. `unsupportedAdditions` は共通部分列を取るので O(入力 × 出力) 掛かる。
    ///    暴走した生成をそこへ渡す前に切る早期打ち切りとして効く（`isPlausible` と同じ役)。
    /// 2. **「整形結果にコードフェンスは決して現れない」は入力に依らない絶対条件**である。
    ///    追加字数の検査は「入力に無い文字」を見るので、原理的には
    ///    **入力にフェンスが含まれれば通してしまう**（音声認識の出力にバッククォートは
    ///    現れないので実際には起きないが、FR-6 の辞書は利用者が手で書く）。
    ///    その 1 点でだけこの門は独立で、検査 `rejectsCodeFenceEvenWhenInputContainsIt` が
    ///    そこを駆動している。
    static func containsCodeFence(_ output: String) -> Bool {
        output.contains("```")
    }

    /// 出力が入力の**変換**になっているか。**入力に無い語がどれだけ足されたか**で測る。
    ///
    /// **長さとコードフェンスだけでは、入力と同じくらいの長さの逸脱を止められない**
    /// （実機で観測 / 2026-08-14。要件定義書 §2.8.5）:
    ///
    /// ```
    /// raw    : 東京の天気どんな感じですか？   （14 字）
    /// refined: 東京の天気は晴れています。     （13 字。比 0.93 で `isPlausible` を通る）
    /// ```
    ///
    /// **モデルが質問に答え、その答えが利用者の発話として挿入された。** 内容は作り話で
    /// ある（モデルは天気を知らない）。テキストを失うより重い——言っていないことを
    /// 言ったことにしている。
    ///
    /// ## フェーズ 1 の指標が誤っていた（V-37 / 実測 2026-08-15）
    ///
    /// 最初の指標は「共通部分列 / **短い方**の長さ」だった。これは
    /// **max(入力の残存率, 出力の由来率)** に等しく、**2 方向の甘い方**を採る。
    /// 結果、**入力が丸ごと残っていれば追加は何字あっても 1.000** になる——
    /// **追加に対して原理的に盲目**だった。
    ///
    /// 実機で実際に起きていたこと（`say -v Kyoko` のフィクスチャ 6 秒スライス）:
    ///
    /// ```
    /// raw    : 本日は…まず前回のミーティングの振替                    （36 字）
    /// refined: 本日は…まず前回のミーティングの振替についてお話しします。（47 字）
    /// ```
    ///
    /// **「についてお話しします」は誰も言っていない。** 旧指標は 1.000 を返し、
    /// 長さの検査も通り、**利用者の欄へ入っていた。**
    /// 10 秒スライス（56 字 → 96 字。40 字ぶんの会議報告が丸ごと作り話）が捨てられたのは、
    /// 指標が捕まえたからではなく**長さの上限に偶然引っ掛かった**だけである。
    ///
    /// ## 発話長への依存は「逆向き」だった
    ///
    /// V-37 の当初の疑いは「長い発話ほど比が下がって正当な整形が落ちる」だったが、
    /// **実測は逆**で、旧指標は長いほど**上がった**（19 字 0.933 → 124 字 0.991。
    /// フィラーが長文では相対的に小さくなるため）。
    /// **5〜124 字の 9 例すべてで正当な整形は受け入れられていた。**
    /// A4 が観測した「56 字が 10/10 捨てられる」は発話長の問題ではなく、
    /// **音声を 10 秒で切ったために発話が文の途中で終わっていた**ことによる。
    ///
    /// ## 残存率の向きは閾値で分けられない（判定に使わない理由）
    ///
    /// | 操作 | 例 | 残存率 |
    /// |---|---|---|
    /// | フィラー削除（短文） | `えー、はい` → `はい。` | **0.400** |
    /// | フィラー削除（中） | `あのー、会議は、えっと明日です` → `会議は明日です。` | 0.467 |
    /// | **逸脱（回答）** | `東京の天気どんな感じですか？` → `東京の天気は晴れています。` | **0.429** |
    ///
    /// **0.400 と 0.429 は分けられない。** フィラー削除は「消す」操作で、
    /// 短い発話ほど消える割合が大きい。**分かれるのは消した量ではなく足した量である。**
    /// `coverageRatio` は計測のために残してあるが、判定には使わない。
    ///
    /// ## 用語の正規化（FR-6）を逸脱と分ける工夫は残してある
    ///
    /// `ジーエイエスを使いました` → `Google Apps Script を使いました。` は、
    /// 素で測ると **16 字の追加**（許容量 0 字はもちろん、逸脱の最小 6 字も大きく超える）。
    /// だから `accept` は**頼んだ置換も由来として認めてから**測る
    /// （`permittingVocabulary(_:terms:)`）。認めた後は追加 0 字になる。
    /// **辞書を渡さなければ同じ出力が落ちる**ことも検査で固定してある。
    /// **置換は任意であって必須ではない**（置き換えてしまうと、モデルが置換しなかった
    /// ときに入力そのままの出力まで落ちる。実運用でそれが起きた）。
    ///
    /// ## フェーズ 2 最終レビュー: 「間隙 3」も破れていた（V-38 / 実測 2026-08-15）
    ///
    /// 追加字数へ置き換えた後、閾値は「正当側の最大 2 と逸脱側の最小 5 の間隙」に置いていた。
    /// **この間隙は 13 入力の標本にしか無かった。** 標本を広げた実測（48 入力）で、
    /// **正当な数量正規化が閾値ちょうどの 3 字に届いた**——
    /// `…前年比で百二十パーセントでした` → `…前年比で120％でした。` は追加 3 で、
    /// **余裕は 0 だった**（`千二百` → `1,200` なら 4 字で落ちる）。
    /// 反証役の指摘（`review-6-refute.md` §5）は、実際の標本で裏付けられた。
    ///
    /// **2 回続けて閾値を動かして失敗している。だから 3 回目は閾値をいじっていない。
    /// 曖昧な類そのものを消した。**
    ///
    /// ## 直し方: 曖昧な類をプロンプトで消し、許容量を 0 にした
    ///
    /// 数量表記の正規化は、**それ自体は逸脱ではない**から許容するしかなく、
    /// 許容した量はそのまま逸脱にも開いていた。`RefinementPrompt` の規則 5
    /// （数字の表記を変えない）で**この類を起こさせない**ようにした結果、
    /// **観測された正当な整形の追加字数は全部 0 になった**（実測の表は
    /// `maximumUnsupportedAdditions` にある）。だから許容量は 0 である。
    ///
    /// 言い換えると、この検査が要求するのは 1 つの性質だけである:
    ///
    /// > **整形結果は、句読点・空白・大文字小文字を除けば、入力の部分列でなければならない。**
    ///
    /// 整形は「フィラーを削る・言い直しを畳む・句読点を補う」——**削る操作と、
    /// 自由に足してよい文字の追加**しかない。閾値ではなく、操作の定義そのものである。
    ///
    /// ## この検査が**原理的に捕まえられないもの**（正本 §2.8 に明記した）
    ///
    /// 見ているのは**足された文字**だけなので、**削ることで意味が変わる逸脱は素通りする。**
    ///
    /// | 形 | 例 | この検査 |
    /// |---|---|---|
    /// | **削るだけの要約** | `…が抜けてるのでそこを追加したいです` → `…を追加したいです。` | **通る** |
    /// | **否定の脱落** | `行きたくないです` → `行きたいです` | **通る**（部分列なので） |
    /// | 語尾まで書き換えた要約（L-5 の実測例） | `…追加したいです` → `…追加します。` | 落ちる（追加 1） |
    /// | 語の入れ替え | `成功` → `失敗。` | 落ちる（追加 2） |
    /// | 語順の入れ替え | `A は B より大きい` → `B は A より大きい` | 落ちる（追加 1 以上） |
    ///
    /// **境目は「意味が変わったか」ではなく「入力に無い文字を使ったか」である。**
    /// L-5（過剰要約）が落ちるのは意味を見ているからではなく、たまたま語尾を
    /// 書き換えていたからにすぎない。**削るだけの逸脱は、どう閾値を動かしても通る。**
    ///
    /// **文字の編集距離を測る指標は意味を見ていない。** 上 2 行は「入力の文字しか使っていない」
    /// ので、どんな閾値でも分けられない。**指標の改良では解けない。**
    /// 安全網は **FR-7（Undo）と、履歴が `rawText` を保持していること**である
    /// （`HistoryEntry.rawText`。整形後だけでなく生テキストも必ず残る）。
    ///
    /// なお **`成功` → `失敗` のような短い意味反転は実機で一度も観測されていない**
    /// （18 の短い発話を実 LLM へ通し、`可` → `可`、`不可` → `不可`、`承認` → `承認`、
    /// `却下` → `却下` と、いずれも反転しなかった。反転例は反証役が手で構成したもの）。
    /// 実機で観測された逸脱は**まとまった量が足される**形だけである（追加 6〜166 字）。
    ///
    /// 共通部分列の長さ。1 行ぶんだけ持って回す。
    static func commonSubsequenceLength(_ a: [Character], _ b: [Character]) -> Int {
        guard !a.isEmpty, !b.isEmpty else { return 0 }
        var previous = [Int](repeating: 0, count: b.count + 1)
        var current = previous
        for i in 1...a.count {
            for j in 1...b.count {
                current[j] = a[i - 1] == b[j - 1] ? previous[j - 1] + 1 : max(previous[j], current[j - 1])
            }
            swap(&previous, &current)
        }
        return previous[b.count]
    }

    /// 入力のどれだけが出力に残ったか。**言われたことが消えていないか**を見る。
    /// **判定には使わない**（`unsupportedAdditions` の doc にある実測のとおり、
    /// この向きは正当な整形と逸脱を分けられない）。計測と報告のために置いてある。
    static func coverageRatio(_ output: String, of expected: String) -> Double {
        let a = Array(expected), b = Array(output)
        guard !a.isEmpty else { return 0 }
        return Double(commonSubsequenceLength(a, b)) / Double(a.count)
    }

    /// 出力のうち、**入力にも句読点にも由来しない文字の数**。
    ///
    /// 判定はこの 1 つで行う。詳細は `maximumUnsupportedAdditions`。
    static func unsupportedAdditions(_ output: String, of expected: String) -> Int {
        let a = content(of: expected)
        let b = content(of: output)
        guard !b.isEmpty else { return 0 }
        return b.count - commonSubsequenceLength(a, b)
    }

    /// **整形が自由に足してよい文字を落とした残り**——これが「言った内容」である。
    ///
    /// 落とすのは 2 種類。
    ///
    /// **句読点と空白**: 整形の仕事の一つが「句読点を適切に補う」ことなので勘定に入れない。
    /// 入れると**節の多い長い発話ほど落ちる**指標になり、V-37 が疑った長さ依存を
    /// 直した側で作り込むことになる（実測: 句読点の少ない 49 字の発話で読点 2 + 句点 1）。
    ///
    /// **大文字小文字**: 英語では文頭の大文字化が正当な整形として起きる。実測
    /// （2026-08-15 / en-US の 6 発話）で `so the meeting is at ten…` → `The meeting is at ten…`、
    /// `you know the build is failing…` → `Build is failing…` と、**大文字化だけで
    /// 追加 1 字**が付いた。許容量 0 では、これを畳まないと**英語の整形が丸ごと落ちる**。
    /// 畳んだ後は 6 発話すべて追加 0 字になる。
    static func content(of text: String) -> [Character] {
        text.lowercased().filter { character in
            !character.unicodeScalars.allSatisfy(freelyInsertable.contains)
        }
    }

    private static let freelyInsertable = CharacterSet.whitespacesAndNewlines
        .union(.punctuationCharacters)

    /// 入力に無い語の許容量。**句読点・空白・大文字小文字は数に入らない**ので、これは
    /// 「利用者が言っていない語をどれだけ通すか」そのものである。**0 字である。**
    ///
    /// ## 実測（2026-08-15 / MacBook Pro M3 / macOS 26.5.2 / temperature 0）
    ///
    /// **製品のプロンプトそのもの**（規則 5 入り）で、発話長 1〜76 字・日英 71 発話を
    /// 実 LLM へ通した。**70 発話が応答し、うち 61 が受理された。追加字数の分布:**
    ///
    /// | 種別 | 標本 | 追加字数 |
    /// |---|---|---|
    /// | 極短（`はい` `うん` `可` `承認` `却下` `中止` 等） | 17 | **すべて 0** |
    /// | フィラー削除（5〜37 字） | 12 | **すべて 0** |
    /// | 言い直しの畳み込み | 3 | **すべて 0** |
    /// | 句読点の補完（35〜49 字。読点 2 + 句点 1） | 4 | **すべて 0** |
    /// | 数量表記（漢数字・算用数字・日付・パーセント） | 12 | **すべて 0** |
    /// | 長文（56〜82 字） | 6 | **すべて 0** |
    /// | 英語（大文字小文字を畳んだ後） | 4 | **すべて 0** |
    /// | 命令文に読める発話で整形された分 | 3 | **すべて 0** |
    /// | **逸脱: 質問への回答** | 2 | **6** |
    /// | **逸脱: 続きの捏造**（文の途中で切れた発話） | 3 | **7 / 10 / 38** |
    /// | **逸脱: 日本語への翻訳**（en-US の 6 発話中 2） | 2 | **14 / 15** |
    /// | **逸脱: 依頼への回答**（前置き・コード片） | 2 | **128 / 166** |
    ///
    /// **受理された 61 発話は 61/61 が 0 字。逸脱側の最小は 6 字。1〜5 は 1 例も無い。**
    /// 間隙を探して真ん中へ置くのではなく、**正当側の観測値そのもの（0）を線にしてある。**
    ///
    /// 別の標本（規則 5 抜きの比較実験）では、追加 6 / 7 字の逸脱をもう 2 種観測した:
    /// `よろしく` → `よろしくお願いします。`（短い発話への言い足し）、
    /// `資料を上げておきました` → `資料をアップしました。`（言い換え）。**どちらも落ちる。**
    ///
    /// ## なぜ「間隙の真ん中」ではなく 0 なのか
    ///
    /// 閾値を動かす直し方は**2 回続けて破れた**（V-37 の残存率、V-38 の間隙 3）。
    /// どちらも「観測した標本の間に線を引いた」ために、標本の外で破れた。
    /// **0 は標本から引いた線ではない。「整形は足す操作ではない」という定義である。**
    /// 標本が増えても動かない。
    ///
    /// **代償は正しく理解しておくこと。** 許容量 0 は、モデルが 1 字でも
    /// 入力に無い文字を足せば整形を捨てる。**捨てたときに起きるのは生テキストの挿入**
    /// （利用者が言ったことは失われない）であり、**逸脱を通すより軽い**。
    /// この非対称が、線を厳しい側へ倒す根拠である。
    ///
    /// - Note: **この量は発話長に依存しない。** 句読点を勘定から外したことで、
    ///   長い発話ほど不利になる項が消えている（V-37 の再発防止）。
    /// - Important: **この値を上げるなら、`RefinementPrompt` の規則 5 とセットで考えること。**
    ///   規則 5 を外すと数量正規化が復活し、追加 1〜3 字の**正当な**出力が生まれて
    ///   整形が落ち始める。逆に規則 5 がある限り、上げる理由は実測上どこにも無い。
    static let maximumUnsupportedAdditions = 0

    /// 頼んだ置換（FR-6 の用語辞書）を、**由来として認める形**として入力へ足す。
    ///
    /// **これをしないと、用語の正規化が逸脱と区別できない。**
    /// `ジーエイエスを使いました` → `Google Apps Script を使いました。` は素で測ると
    /// **16 字の追加**で、逸脱の最小（6 字）を大きく超える（上記の表）。
    /// 整形器はこの辞書をプロンプトへ入れて置換を依頼しているので、
    /// **置換後の姿も「期待される入力」である。**
    ///
    /// ## 置き換えてはならない。**両方を残す**（実運用の実測 / 2026-08-15）
    ///
    /// 当初はここで誤認識表記を正規表記へ**置き換えて**いた。
    /// **その形は「置換は必須である」と言っているに等しく、実機で整形を丸ごと落とした。**
    ///
    /// 利用者が辞書に `頭, 列, スレッズ → Threads` を入れた状態で、
    /// **モデルが置換をしなかった**ときの実測（各 3 回・同一）:
    ///
    /// ```
    /// raw     : 頭のAPIが使えるようになったので
    /// 置換後の expected : ThreadsのAPIが使えるようになったので
    /// モデルの出力     : 頭のAPIが使えるようになったので、スレッズをThreadsにしました。
    /// ```
    ///
    /// **`頭` は利用者が実際に言った（認識された）文字なのに、`expected` から消えていたので
    /// 「入力に無い文字」に数えられた。** 出力が入力と 1 字も違わない場合ですら、
    /// 辞書に語を 1 つ入れた瞬間に**追加 1 字**となって拒否される。
    /// **辞書を足すと整形が効かなくなる**——FR-6 が FR-5 を壊していた。
    ///
    /// **置換は「してもよい」であって「しなければならない」ではない。**
    /// だから誤認識表記を消さず、**その直後に正規表記を挿し込む**。
    /// 出力がどちらの表記を採っても（両方を並べても）追加 0 字になり、
    /// **利用者が言っていない語だけが追加として残る。**
    ///
    /// - Note: 実測の裏づけは `RefinerTests` の
    ///   `辞書があってもモデルが置換しなければ、入力そのままの出力を受け入れる`。
    static func permittingVocabulary(_ raw: String, terms: [VocabularyTerm]) -> String {
        var result = raw
        for term in terms {
            for variant in term.misheard where !variant.isEmpty {
                result = result.replacingOccurrences(
                    of: variant, with: variant + term.canonical)
            }
        }
        return result
    }

    /// LLM の出力を整形結果として受け入れるか決める。受け入れないときは nil を返し、
    /// 呼び出し側が生テキストへ縮退する。
    static func accept(
        _ output: String, refinementOf raw: String, terms: [VocabularyTerm] = []
    ) -> String? {
        let trimmed = output.trimmingCharacters(in: .whitespacesAndNewlines)
        // 追加字数は**頼んだ置換も由来として認めた入力**と比べる
        // （`permittingVocabulary` の理由。置換は任意であって必須ではない）。
        let expected = permittingVocabulary(raw, terms: terms)
        // 長さの検査を先に通す。`unsupportedAdditions` は共通部分列を取るので
        // 出力の長さに比例して重くなり、暴走した生成をそのまま渡したくない。
        guard !trimmed.isEmpty,
              !containsCodeFence(trimmed),
              isPlausible(trimmed, refinementOf: raw),
              keepsSomeContent(trimmed, of: expected),
              unsupportedAdditions(trimmed, of: expected) <= maximumUnsupportedAdditions
        else { return nil }
        return trimmed
    }

    /// **句読点だけの出力を落とす。**
    ///
    /// `unsupportedAdditions` は「出力の内容文字」を数えるので、内容が空なら 0 を返す
    /// ——**許容量 0 でも `。` や `...` だけの出力が通ってしまう。**
    /// 許容量が 3 だった頃は他の門が塞いでいたわけでもなく、**元から開いていた穴**である
    /// （実機では観測していない。閉じる費用がほぼ無いので閉じる）。
    static func keepsSomeContent(_ output: String, of expected: String) -> Bool {
        content(of: expected).isEmpty || !content(of: output).isEmpty
    }
}

/// 指定時間内に完了しなければ nil を返す。**打ち切った作業の完了は待たない。**
///
/// `withTaskGroup` はスコープを抜ける際に子タスクの完了を待つ。その形で書くと、
/// 作業が打ち切りに応じない場合に呼び出しの実時間が `timeout` を超え、
/// **ユーザーへの文字入力がその間ずっと止まる。**
/// 実測（キャンセルを尊重しない 2 秒の作業を 50ms で打ち切る）:
/// 待つ実装 2.132 秒 / 待たない実装 0.059 秒。
///
/// `FoundationModels` の `respond` は実際にはキャンセルに応じる（暴走した生成を
/// 500ms で打ち切っても 0.529 秒で返った）が、**そこに依存しない形にしてある。**
/// 打ち切った生成はデーモン側で走り続けうる。挿入が止まるよりはましと判断した。
///
/// 打ち切った生成が次の発話と衝突して `concurrentRequests` になることは無い。
/// セッションはリクエストごとに作られ、次の発話は別のセッションを使う。
func withTimeout(_ timeout: Duration, _ work: @escaping @Sendable () async -> String?) async -> String? {
    let stream = AsyncStream<String?>.makeStream()

    let workTask = Task {
        stream.continuation.yield(await work())
        stream.continuation.finish()
    }
    let timeoutTask = Task {
        try? await Task.sleep(for: timeout)
        stream.continuation.yield(nil)
        stream.continuation.finish()
    }
    // 待ちはしないが cancel は送る。止められる作業なら止めて計算資源を返す。
    defer {
        workTask.cancel()
        timeoutTask.cancel()
    }

    var results = stream.stream.makeAsyncIterator()
    return await results.next() ?? nil
}
